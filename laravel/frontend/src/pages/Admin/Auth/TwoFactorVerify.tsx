import { Head, useForm } from '@inertiajs/react';
import { useState, type FormEvent } from 'react';

export default function TwoFactorVerify() {
    const [useRecovery, setUseRecovery] = useState(false);

    const verifyForm = useForm({
        code: '',
    });

    const recoveryForm = useForm({
        code: '',
    });

    function submitVerify(event: FormEvent<HTMLFormElement>) {
        event.preventDefault();
        verifyForm.post('/admin/2fa/verify');
    }

    function submitRecovery(event: FormEvent<HTMLFormElement>) {
        event.preventDefault();
        recoveryForm.post('/admin/2fa/recovery');
    }

    return (
        <>
            <Head title="Two-Factor Verification" />

            <div className="flex min-h-screen items-center justify-center bg-gradient-to-br from-slate-950 via-slate-900 to-indigo-950 p-4">
                <div className="w-full max-w-md rounded-3xl bg-slate-900/90 p-8 shadow-2xl border border-slate-800 text-white">
                    <div className="flex items-center gap-3 mb-6">
                        <span className="flex h-10 w-10 items-center justify-center rounded-xl bg-indigo-500/20 border border-indigo-500/30">
                            <i className="fas fa-shield-halved text-indigo-400" aria-hidden="true" />
                        </span>
                        <div>
                            <h1 className="text-xl font-bold">Two-Factor Verification</h1>
                            <p className="text-xs text-slate-400">Confirm administrative identity</p>
                        </div>
                    </div>

                    {!useRecovery ? (
                        <>
                            <p className="text-sm text-slate-300 mb-6 leading-relaxed">
                                Enter the 6-digit security code generated by your authenticator device.
                            </p>

                            {verifyForm.errors.code && (
                                <div className="mb-4 rounded-xl border border-red-500/30 bg-red-500/10 p-3 text-sm text-red-400">
                                    {verifyForm.errors.code}
                                </div>
                            )}

                            <form onSubmit={submitVerify} className="space-y-4">
                                <div>
                                    <input
                                        id="code"
                                        type="text"
                                        inputMode="numeric"
                                        autoComplete="one-time-code"
                                        placeholder="123456"
                                        required
                                        autoFocus
                                        value={verifyForm.data.code}
                                        onChange={(e) => verifyForm.setData('code', e.target.value)}
                                        className="block w-full rounded-xl border border-slate-800 bg-slate-950/80 px-4 py-3 text-center text-2xl tracking-[0.3em] font-mono text-white placeholder-slate-600 outline-none transition focus:border-indigo-500 focus:ring-2 focus:ring-indigo-500/20"
                                    />
                                </div>

                                <button
                                    type="submit"
                                    disabled={verifyForm.processing}
                                    className="w-full rounded-xl bg-gradient-to-r from-indigo-600 to-blue-600 px-4 py-3 text-sm font-semibold text-white shadow-lg shadow-indigo-600/30 hover:from-indigo-500 hover:to-blue-500 disabled:opacity-60 transition"
                                >
                                    {verifyForm.processing ? 'Verifying…' : 'Verify'}
                                </button>
                            </form>

                            <div className="mt-6 pt-5 border-t border-slate-800/80 text-center">
                                <button
                                    type="button"
                                    onClick={() => setUseRecovery(true)}
                                    className="text-xs text-indigo-400 hover:text-indigo-300 font-medium transition-colors"
                                >
                                    Lost access to device? Use recovery code
                                </button>
                            </div>
                        </>
                    ) : (
                        <>
                            <p className="text-sm text-slate-300 mb-6 leading-relaxed">
                                Enter one of your emergency backup recovery codes.
                            </p>

                            {recoveryForm.errors.code && (
                                <div className="mb-4 rounded-xl border border-red-500/30 bg-red-500/10 p-3 text-sm text-red-400">
                                    {recoveryForm.errors.code}
                                </div>
                            )}

                            <form onSubmit={submitRecovery} className="space-y-4">
                                <div>
                                    <input
                                        id="recoveryCode"
                                        type="text"
                                        autoComplete="off"
                                        placeholder="abcd-efgh-ijkl"
                                        required
                                        autoFocus
                                        value={recoveryForm.data.code}
                                        onChange={(e) => recoveryForm.setData('code', e.target.value)}
                                        className="block w-full rounded-xl border border-slate-800 bg-slate-950/80 px-4 py-3 text-center text-base font-mono text-white placeholder-slate-600 outline-none transition focus:border-indigo-500 focus:ring-2 focus:ring-indigo-500/20"
                                    />
                                </div>

                                <button
                                    type="submit"
                                    disabled={recoveryForm.processing}
                                    className="w-full rounded-xl bg-gradient-to-r from-indigo-600 to-blue-600 px-4 py-3 text-sm font-semibold text-white shadow-lg shadow-indigo-600/30 hover:from-indigo-500 hover:to-blue-500 disabled:opacity-60 transition"
                                >
                                    {recoveryForm.processing ? 'Consuming Code…' : 'Use Recovery Code'}
                                </button>
                            </form>

                            <div className="mt-6 pt-5 border-t border-slate-800/80 text-center">
                                <button
                                    type="button"
                                    onClick={() => setUseRecovery(false)}
                                    className="text-xs text-indigo-400 hover:text-indigo-300 font-medium transition-colors"
                                >
                                    Back to authenticator code
                                </button>
                            </div>
                        </>
                    )}
                </div>
            </div>
        </>
    );
}
